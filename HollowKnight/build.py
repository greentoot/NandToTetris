"""Regenerate Jack graphics and compile the playable VM folder."""
from pathlib import Path
import shutil
import sys
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def bitmap():
    source = Image.open(HERE / 'assets/logo-source.png').convert('RGBA')
    white = Image.new('RGBA', source.size, 'white')
    white.alpha_composite(source)
    # Fit inside a 448 x 228 area without changing the source proportions.
    scale = min(448 / source.width, 228 / source.height)
    size = (round(source.width * scale), round(source.height * scale))
    logo = white.convert('L').resize(size, Image.Resampling.LANCZOS)
    logo = logo.point(lambda value: 255 if value >= 128 else 0, mode='1')
    screen = Image.new('1', (512, 256), 1)
    screen.paste(logo, ((512 - size[0]) // 2, (256 - size[1]) // 2))
    return screen


def scene_bitmap(name='scene'):
    art = Image.open(HERE / ('assets/' + name + '-background.png')).convert('RGB')
    # Resample to the target screen; final threshold enforces exactly two colors.
    art.thumbnail((512, 256), Image.Resampling.LANCZOS)
    monochrome = art.convert('L').point(lambda value: 255 if value >= 128 else 0, mode='1')
    screen = Image.new('1', (512, 256), 1)
    screen.paste(monochrome, ((512 - art.width) // 2, (256 - art.height) // 2))
    # Use the first room's original HUD pixels in every room, including its backing.
    # This removes the inconsistent HUDs drawn into the generated backgrounds.
    if name != 'scene':
        canonical = scene_bitmap('scene')
        screen.paste(canonical.crop((0, 0, 128, 64)), (0, 0))
    return screen


def generate(screen, class_name='Title'):
    words = []
    for y in range(256):
        for x in range(0, 512, 16):
            value = sum((1 << bit) for bit in range(16) if not screen.getpixel((x + bit, y)))
            words.append(value)
    # The display is cleared explicitly so draw() also works after another scene.
    lines = ['// Generated by build.py. Do not edit bitmap words manually.', f'class {class_name} {{',
             '    function void draw() {', '        var Array screen;', '        var int i;',
             '        let screen = 16384;', '        let i = 0;',
             '        while (i < 8192) {', '            let screen[i] = 0;',
             '            let i = i + 1;', '        }']
    for part in range(16):
        lines.append(f'        do {class_name}.part{part}(screen);')
    lines += ['        return;', '    }']
    for part in range(16):
        lines.append(f'    function void part{part}(Array screen) {{')
        for index in range(part * 512, (part + 1) * 512):
            value = words[index]
            if value:
                # Jack integer literals must stay within 0..32767.
                expression = str(value) if value < 32768 else '~' + str(65535 - value)
                lines.append(f'        let screen[{index}] = {expression};')
        lines += ['        return;', '    }']
    lines.append('}')
    (HERE / (class_name + '.jack')).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return words


def main():
    from generate_sprite import generate as generate_sprite, boss_sprite
    sys.path.insert(0, str(ROOT / 'NandStudio'))
    from compiler import compile_jack

    generate_sprite()
    generate_sprite([boss_sprite(0), boss_sprite(1)], 'Boss')
    images = {'Title': bitmap(), 'Scene': scene_bitmap(),
              'Crossing': scene_bitmap('crossing'), 'Arena': scene_bitmap('arena')}
    for name, screen in images.items():
        generate(screen, name)
    output = HERE / 'VM'
    output.mkdir(parents=True, exist_ok=True)
    for name in ('Main', 'Title', 'Scene', 'Crossing', 'Arena', 'Game', 'Sprite', 'Boss'):
        compile_jack(HERE / (name + '.jack'), output / (name + '.vm'))
    for name in ('Array', 'Keyboard', 'Math', 'Memory', 'Output', 'Screen', 'String', 'Sys'):
        shutil.copyfile(ROOT / 'NandStudio' / 'vendor' / 'os' / (name + '.vm'),
                        output / (name + '.vm'))
    print('VM prêts dans', output)


if __name__ == '__main__':
    main()
