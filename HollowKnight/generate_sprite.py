"""Code-authored Hornet silhouette; masked byte blits, two poses and directions."""
from PIL import Image, ImageDraw, ImageOps
from pathlib import Path
import math
HERE = Path(__file__).resolve().parent


from hornet_frames import sprite


def boss_sprite(frame):
    im = Image.new('RGBA', (48, 64))
    d = ImageDraw.Draw(im)
    # Wing strokes, segmented abdomen and pointed tail of the reference boss.
    for points in ([(17, 28), (0, 21 + frame * 3), (4, 35), (17, 39)],
                   [(30, 28), (47, 21 + frame * 3), (44, 35), (30, 39)]):
        d.polygon(points, fill='white', outline='black')
    d.polygon([(15, 41), (34, 41), (35, 52), (28, 63), (18, 55)], fill='white', outline='black')
    d.ellipse((12, 31, 36, 54), fill='white', outline='black', width=2)
    d.arc((12, 34, 36, 48), 0, 180, fill='black', width=2)
    d.arc((15, 40, 35, 54), 0, 180, fill='black', width=2)
    ring = []
    for i in range(36):
        angle = i * math.pi / 18
        radius = 20 if i % 2 == 0 else 17
        ring.append((24 + round(math.cos(angle) * radius), 21 + round(math.sin(angle) * radius)))
    d.polygon(ring, fill='black', outline='white')
    d.polygon([(12, 19), (15, 12), (21, 15), (27, 12), (35, 17),
               (36, 26), (30, 33), (23, 35), (15, 30)], fill='white', outline='black')
    d.ellipse((15, 22, 20, 29), fill='black')
    d.ellipse((27, 21, 33, 28), fill='black')
    d.line([(21, 36), (17, 42), (22, 44)], fill='black', width=2)
    d.line([(28, 36), (31, 42), (27, 44)], fill='black', width=2)
    return im


def generate(images=None, class_name='Sprite'):
    if images is None:
        from hornet_frames import generate as import_hornet
        return import_hornet()
    width, height = images[0].size
    stride = width // 8
    frame_size = stride * height
    ink, mask = [], []
    for im in images:
        for y in range(height):
            for x in range(0, width, 8):
                m = v = 0
                for bit in range(8):
                    r, g, b, a = im.getpixel((x + bit, y))
                    if a:
                        m |= 1 << bit
                        if r < 128: v |= 1 << bit
                ink.append(v)
                mask.append(m)
    lines = ['// Generated by generate_sprite.py.', f'class {class_name} {{',
             '    static Array ink, mask;', '    function void init() {',
             '        if (~(ink = 0)) { return; }',
             f'        let ink = Array.new({len(ink)});', f'        let mask = Array.new({len(mask)});']
    parts = (len(ink) + 95) // 96
    for part in range(parts): lines.append(f'        do {class_name}.part{part}();')
    lines += ['        return;', '    }']
    for part in range(parts):
        lines.append(f'    function void part{part}() {{')
        for i in range(part * 96, min((part + 1) * 96, len(ink))):
            lines += [f'        let ink[{i}] = {ink[i]};', f'        let mask[{i}] = {mask[i]};']
        lines += ['        return;', '    }']
    lines += ['''    function void draw(int x, int y, int facing, int frame) {
        var Array screen;
        var int row, col, source, pixel, address, m, v;
        let screen = 16384;
        let source = ((facing * 2) + frame) * 192;
        let row = 0;
        while (row < 48) {
            let col = 0;
            while (col < 4) {
                let m = mask[source];
                if (~(m = 0)) {
                    let v = ink[source];
                    let pixel = x + (col * 8);
                    let address = ((y + row) * 32) + (pixel / 16);
                    if ((pixel & 8) = 8) {
                        let m = m * 256;
                        let v = v * 256;
                    }
                    let screen[address] = (screen[address] & (~m)) | v;
                }
                let source = source + 1;
                let col = col + 1;
            }
            let row = row + 1;
        }
        return;
    }
}''']
    code = '\n'.join(lines).replace('* 192;', f'* {frame_size};')
    code = code.replace('row < 48', f'row < {height}').replace('col < 4', f'col < {stride}')
    (HERE / (class_name + '.jack')).write_text(code + '\n')
    return images


if __name__ == '__main__': generate()
